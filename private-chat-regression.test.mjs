import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { webcrypto, createHash } from 'node:crypto';
import vm from 'node:vm';
import { parseCombinedParts } from './combined-response.mjs';
import { parseCustomFormat } from './utils.js';
import { archiveText } from './archive-input.mjs';
import { sourceHashes, receiptProgress } from './card-archive.mjs';
import { moduleStatus } from './module-progress.mjs';
import { cwbCompleteDefaultSettings, DEFAULT_TIMELINE_INCREMENTAL_PROMPT } from './defaults.js';

const enabled = process.env.CWB_PRIVATE_CHAT_FIXTURE && process.env.CWB_PRIVATE_RESPONSES_FIXTURE;
for (const outputFormat of ['markers', 'json', 'malformed']) {
test(`private source replay (${outputFormat}): empty books, floor 1 through the end, readback and reload`, { skip: !enabled && 'Requires private chat and assistant-authored model replies; never publishes either fixture' }, async () => {
    const rows = readFileSync(process.env.CWB_PRIVATE_CHAT_FIXTURE, 'utf8').trim().split('\n').map(JSON.parse);
    const chat = rows.slice(1), original = JSON.stringify(chat);
    const replies = JSON.parse(readFileSync(process.env.CWB_PRIVATE_RESPONSES_FIXTURE, 'utf8'));
    const names = [...new Set(Object.values(replies).flatMap(reply => parseCombinedParts(reply).profiles.value).map(block => parseCustomFormat(block)).filter(row => row.档案类型 !== '主角').map(row => row.姓名))];
    const books = new Map([
        ['主世界书', { entries: {} }],
        ['角色分卷', { entries: { 0: { uid: 0, key: ['CWB:世界书目录'], content: names.map(name => `姓名: "${name}"`).join('\n') } } }],
    ]);
    const contextData = { chatId: 'private-replay', chatMetadata: { integrity: 'private-replay' }, characterId: 0, name1: rows[0].user_name || '主角', characters: [{ avatar: 'PrivateTest.png', data: { extensions: { world: '主世界书' } } }], chat };
    const requests = [], receipts = [], nodes = new Map(), eventHooks = new Map();
    const $ = id => {
        if (!nodes.has(id)) nodes.set(id, { text(value) { if (value !== undefined) this.value = value; return this; }, prop() { return this; }, attr() { return this; } });
        return nodes.get(id);
    };
    const settings = { enabled: true, autoUpdate: false, incremental: true, threshold: 25, responseLength: 4096, worldbookTarget: 'primary', multiWorldbookRouting: true, excludedWorldbooks: [],
        breakPrompt: cwbCompleteDefaultSettings.cwb_break_armor_prompt,
        fullPrompt: cwbCompleteDefaultSettings.cwb_char_card_prompt, incrementalPrompt: cwbCompleteDefaultSettings.cwb_incremental_char_card_prompt,
        timelineIncrementalPrompt: DEFAULT_TIMELINE_INCREMENTAL_PROMPT };
    const script = { getRequestHeaders: () => ({}), main_api: 'openai',
        generateRaw: async () => { throw Error('Archive must not use cleaned generation'); },
        createRawPrompt: (prompt, _api, _instruct, _quiet, system) => [{ role: 'system', content: system }, ...prompt],
        extractMessageFromData: data => data.choices[0].message.content,
        event_types: { CHAT_COMPLETION_SETTINGS_READY: 'settings-ready' },
        eventSource: { on(event, fn) { eventHooks.set(event, fn); }, removeListener(event, fn) { if (eventHooks.get(event) === fn) eventHooks.delete(event); } },
    };
    const openai = { sendOpenAIRequest: async (_type, prompt) => {
        const data = { messages: prompt.filter(Boolean), max_tokens: 2048 };
        eventHooks.get('settings-ready')?.(data);
        assert.equal(data.max_tokens, 4096);
        const input = prompt.at(-1).content;
        const range = input.match(/【本轮新增聊天：第 (\d+)-(\d+) 楼】/);
        assert.ok(range, 'original floor range stays explicit');
        const key = range[1] + '-' + range[2];
        assert.ok(replies[key], 'every planned source range has an independently authored replay reply');
        assert.ok(!/<(?:image|UpdateVariable|JSONPatch|Analysis|part_thinking)\b/i.test(input));
        requests.push({ start: Number(range[1]), end: Number(range[2]), characters: input.length });
        // These replies were generated by the assistant from the supplied chat,
        // not by the user's remote model. Keep that distinction explicit.
        let content = replies[key];
        if (outputFormat === 'json') {
            const parts = parseCombinedParts(content);
            content = JSON.stringify({ 角色档案: parts.profiles.value.map(parseCustomFormat), ...parts.timeline.value, ...parts.relationships.value });
        }
        if (outputFormat === 'malformed' && requests.length === 1) content = '未提供可解析的数据';
        return { choices: [{ message: { content }, finish_reason: 'stop' }] };
    } };
    const extensions = { getContext: () => contextData, extension_settings: { cwb_system_api: settings } };
    const world = { world_names: [...books.keys()], selected_world_info: ['角色分卷'], world_info: {},
        loadWorldInfo: async name => structuredClone(books.get(name)),
        saveWorldInfo: async (name, book) => { books.set(name, structuredClone(book)); },
        createWorldInfoEntry: (_name, book) => { const uid = Math.max(-1, ...Object.keys(book.entries).map(Number)) + 1; return book.entries[uid] = { uid }; },
    };
    const document = { getElementById: () => ({ open: false }) };
    const context = vm.createContext({ crypto: webcrypto, TextEncoder, structuredClone, AbortController, console, setTimeout, clearTimeout, $, document, window: {},
        fetch: async (_url, options) => ({ ok: true, json: async () => structuredClone(books.get(JSON.parse(options.body).name)) }) });
    const modules = new Map(), root = dirname(fileURLToPath(import.meta.url));
    const load = async id => {
        if (modules.has(id)) return modules.get(id);
        const values = id === '/script.js' ? script : id === '/scripts/openai.js' ? openai : id === '/scripts/extensions.js' ? extensions : id === '/scripts/world-info.js' ? world : null;
        const module = values ? new vm.SyntheticModule(Object.keys(values), function () { for (const [key, value] of Object.entries(values)) this.setExport(key, value); }, { context, identifier: id })
            : new vm.SourceTextModule(readFileSync(id, 'utf8'), { context, identifier: id });
        modules.set(id, module);
        return module;
    };
    const core = await load(resolve(root, 'core.js'));
    await core.link((specifier, parent) => load(specifier.startsWith('/') ? specifier : resolve(dirname(parent.identifier), specifier)));
    await core.evaluate();
    const outcome = await core.namespace.batchUpdate(settings, undefined, { automatic: true });
    const lore = modules.get(resolve(root, 'lorebook.js')).namespace;
    for (const module of ['profiles', 'timeline', 'relationships']) {
        const status = moduleStatus(await lore.getModuleProgress(), module, chat.length);
        if (outputFormat === 'malformed') {
            assert.equal(status.through, 0, 'invalid output must not advance the first batch');
            assert.deepEqual(JSON.parse(JSON.stringify(status.failed)), [[0, 14]]);
        } else {
            assert.equal(status.through, chat.length, module + ' is verified through the actual last floor');
            assert.equal(status.failed.length, 0);
        }
    }
    const allFloors = requests.flatMap(({ start, end }) => Array.from({ length: end - start + 1 }, (_, i) => start + i));
    assert.deepEqual(allFloors, chat.map((_, i) => i + 1), 'source starts at 1 and is covered exactly once, no gaps or truncation');
    const profiles = (await lore.getCardArchiveEntries()).entries.filter(entry => entry.key.some(key => key === 'CWB:自动档案' || key === 'CWB:主角档案'));
    if (outputFormat === 'malformed') {
        assert.equal(outcome.failures.length, 1);
        assert.equal(JSON.stringify(chat), original);
        return;
    }
    assert.equal(profiles.length, names.length + 1);
    for (const entry of profiles) assert.equal(entry.bookName, entry.key.includes('CWB:主角档案') ? '主世界书' : '角色分卷');
    lore.resetArchiveLocation();
    assert.equal(moduleStatus(await lore.getModuleProgress(), 'profiles', chat.length).through, chat.length, 'progress survives fresh server reads');
    const beforeRepeat = requests.length;
    await core.namespace.batchUpdate(settings);
    assert.equal(requests.length, beforeRepeat, 'rerun calls no model when complete');
    assert.equal(JSON.stringify(chat), original, 'input file snapshots, swipes and message text remain untouched');
    if (process.env.CWB_PRIVATE_WORLDBOOK_FIXTURE) {
        const book = JSON.parse(readFileSync(process.env.CWB_PRIVATE_WORLDBOOK_FIXTURE, 'utf8'));
        const ledger = JSON.parse(Object.values(book.entries).find(entry => entry.key?.includes('CWB:更新状态')).content);
        const hashes = await sourceHashes(chat, text => createHash('sha256').update(text).digest('hex'));
        const saved = receiptProgress(ledger.receipts, hashes);
        for (const module of ['profiles', 'timeline', 'relationships']) assert.equal(moduleStatus(saved, module, chat.length).through, 153);
    }
    console.log(JSON.stringify({ privateReplay: { outputFormat, sourceFloors: chat.length, generatedReplyBatches: requests.length, persistedProfiles: profiles.length, firstFloor: allFloors[0], lastFloor: allFloors.at(-1), repeatModelCalls: requests.length - beforeRepeat, maximumRequestCharacters: Math.max(...requests.map(row => row.characters)) } }));
});

}
